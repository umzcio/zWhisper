import AppKit
import ApplicationServices

/// Architecture §3.6.
struct PasteReceipt: Sendable {
    /// Pasteboard changeCount after our write (diagnostics, §3.6).
    let changeCount: Int
    /// Full pre-paste clipboard archive for Undo paste (§4.3).
    let snapshot: [NSPasteboard.PasteboardType: Data]
    /// Frontmost app at paste time, for "Pasted to {app}" (§4.3).
    let targetApp: String
    /// False when Accessibility is missing and we degraded to clipboard-only (§8).
    let didPaste: Bool
}

enum PasteError: Error {
    case clipboardWriteFailed
}

/// Architecture §3.6 contract.
protocol PasteControllerProtocol: Sendable {
    func paste(text: String, restoreClipboard: Bool) async throws -> PasteReceipt
    /// "Undo paste" (§4.3): restores the pre-paste clipboard snapshot. We
    /// deliberately do not try to delete text from the target app (§3.6).
    func undo(_ receipt: PasteReceipt) async
    /// Auto-paste off (§6.6): result goes to the clipboard without ⌘V.
    func copy(text: String) async
}

/// Full paste sequence (architecture §8): snapshot the clipboard → write the
/// transcript → read the frontmost app for the toast label → post CGEvent ⌘V →
/// wait until the target has actually read the transcript → restore the
/// snapshot when Settings → Paste "Restore clipboard" is on.
///
/// The restore is gated on a real read, never on a timer: a target that
/// handles ⌘V late (a stalled browser tab) would otherwise paste the restored
/// previous clipboard — possibly a password — instead of the dictation.
@MainActor
final class PasteController: PasteControllerProtocol {
    /// Accessibility prompt is shown at most once per launch (§8).
    private var didPromptForAccessibility = false

    /// How long the transcript stays on the clipboard waiting for the target
    /// to read it; past this the restore is skipped, never forced.
    nonisolated static let readTimeout: Duration = .milliseconds(1500)
    /// After the first read, room for a paste handler that reads twice.
    nonisolated static let readGrace: Duration = .milliseconds(150)
    /// Kept alive while its lazy item may still be on the clipboard.
    private var provider: TranscriptProvider?

    func paste(text: String, restoreClipboard: Bool) async throws -> PasteReceipt {
        let pasteboard = NSPasteboard.general
        let snapshot = Self.snapshot(pasteboard)

        pasteboard.clearContents()
        let provider = restoreClipboard ? TranscriptProvider(text: text) : nil
        self.provider = provider
        if let provider {
            // Served lazily so the read is observable; marked transient so
            // clipboard managers neither record it nor trip the read signal.
            let item = NSPasteboardItem()
            item.setDataProvider(provider, forTypes: [.string])
            item.setData(Data(), forType: .transient)
            item.setData(Data(), forType: .autoGenerated)
            guard pasteboard.writeObjects([item]) else { throw PasteError.clipboardWriteFailed }
        } else {
            guard pasteboard.setString(text, forType: .string) else {
                throw PasteError.clipboardWriteFailed
            }
        }
        let changeCount = pasteboard.changeCount

        let targetApp = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""
        let trusted = AXIsProcessTrusted()
        if !trusted, !didPromptForAccessibility {
            didPromptForAccessibility = true
            // Literal key: kAXTrustedCheckOptionPrompt is a C var (not concurrency-safe).
            let options = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
            _ = AXIsProcessTrustedWithOptions(options)
        }

        var didPaste = false
        if trusted {
            Self.postCommandV()
            didPaste = true
        }

        // Restore only after a real paste; when degraded (§8) the transcript
        // must stay on the clipboard so the user can ⌘V manually.
        if let provider, didPaste {
            if await provider.waitForRead(timeout: Self.readTimeout) {
                try? await Task.sleep(for: Self.readGrace)
                // Something else wrote the clipboard meanwhile — keep theirs.
                if pasteboard.changeCount == changeCount {
                    Self.restore(snapshot, to: pasteboard)
                }
            } else {
                AppState.logToStderr("paste: target never read the transcript; clipboard left as-is")
            }
        }
        return PasteReceipt(changeCount: changeCount, snapshot: snapshot, targetApp: targetApp, didPaste: didPaste)
    }

    func undo(_ receipt: PasteReceipt) async {
        Self.restore(receipt.snapshot, to: .general)
    }

    func copy(text: String) async {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboard.PasteboardType: Data] {
        var snapshot: [NSPasteboard.PasteboardType: Data] = [:]
        for item in pasteboard.pasteboardItems ?? [] {
            for type in item.types {
                if let data = item.data(forType: type) {
                    snapshot[type] = data
                }
            }
        }
        return snapshot
    }

    private static func restore(_ snapshot: [NSPasteboard.PasteboardType: Data], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let item = NSPasteboardItem()
        for (type, data) in snapshot {
            item.setData(data, forType: type)
        }
        pasteboard.writeObjects([item])
    }

    /// Serves the transcript on demand and records that it was read.
    private final class TranscriptProvider: NSObject, NSPasteboardItemDataProvider {
        private let text: String
        private(set) var wasRead = false

        init(text: String) {
            self.text = text
        }

        func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
            item.setString(text, forType: type)
            wasRead = true
        }

        @MainActor
        func waitForRead(timeout: Duration) async -> Bool {
            let deadline = ContinuousClock.now + timeout
            while !wasRead, ContinuousClock.now < deadline {
                try? await Task.sleep(for: .milliseconds(10))
            }
            return wasRead
        }
    }

    /// ⌘V as a hardware-sourced keyboard event (§8).
    private static func postCommandV() {
        let source = CGEventSource(stateID: .hidSystemState)
        let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true)
        keyDown?.flags = .maskCommand
        let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false)
        keyUp?.flags = .maskCommand
        keyDown?.post(tap: .cghidEventTap)
        keyUp?.post(tap: .cghidEventTap)
    }
}
